import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

test("offline builds handle empty topics, prune only generated HTML, and repeat deterministically", async () => {
  const directory = await mkdtemp(path.join(os.tmpdir(), "ai-ranking-build-test-"));
  try {
    await cp(path.join(root, "scripts"), path.join(directory, "scripts"), { recursive: true });
    await cp(path.join(root, "assets"), path.join(directory, "assets"), { recursive: true });
    await cp(path.join(root, "package.json"), path.join(directory, "package.json"));
    const records = Array.from({ length: 41 }, (_, index) => ({
      rank: index + 1, name: `Fixture ${index}`, url: `https://www.hvoyai.com/sites/fixture-${index}/`,
      description: "GPT fixture description, not editorial content.", models: ["GPT"], modelCount: 1,
    }));
    const snapshot = (sites) => writeFile(path.join(directory, "data.json"), JSON.stringify({ updatedDate: "2026-09-25", sites }));
    const build = () => execFileSync(process.execPath, ["scripts/build-localized.mjs"], { cwd: directory, env: { ...process.env, AI_API_KEY: "", AI_BASE_URL: "", AI_MODEL: "" }, stdio: "pipe" });
    await snapshot(records);
    build();
    const obsolete = path.join(directory, "ru/page/2/index.html");
    assert.ok((await readFile(obsolete, "utf8")).includes("Generated by AI Ranking"));
    const note = path.join(directory, "ru/page/2/handwritten.txt");
    await writeFile(note, "Keep this user file.");
    await mkdir(path.join(directory, "ru/custom"), { recursive: true });
    const custom = path.join(directory, "ru/custom/index.html");
    await writeFile(custom, '<!doctype html><link rel="canonical" href="https://airanking.github.io/ru/custom/"><nav class="language-switcher">Русский</nav><h1>User-authored page</h1>');
    await snapshot([records[0]]);
    build();
    await assert.rejects(readFile(obsolete), { code: "ENOENT" });
    await assert.rejects(readFile(path.join(directory, "ru/sites/fixture-40/index.html")), { code: "ENOENT" });
    await assert.rejects(readFile(path.join(directory, "page/2/index.html")), { code: "ENOENT" });
    await assert.rejects(readFile(path.join(directory, "ru/gpt-zhongzhuanzhan/page/2/index.html")), { code: "ENOENT" });
    assert.equal(await readFile(note, "utf8"), "Keep this user file.");
    assert.match(await readFile(custom, "utf8"), /User-authored/);
    for (const locale of ["en", "es", "ru", "cn"]) {
      const empty = await readFile(path.join(directory, locale, "kimi-zhongzhuanzhan/index.html"), "utf8");
      assert.match(empty, /class="empty-state"/);
      assert.doesNotMatch(empty, /class="ranking-row"/);
      assert.match(empty, /class="topic-checks"|class="editorial-section topic-checks"/);
    }
    async function outputFiles(current = directory) {
      const result = {};
      for (const entry of await readdir(current, { withFileTypes: true })) {
        if (["scripts", "assets"].includes(entry.name) && current === directory) continue;
        const file = path.join(current, entry.name);
        if (entry.isDirectory()) Object.assign(result, await outputFiles(file));
        else if (/\.(html|xml|txt)$/.test(entry.name)) result[path.relative(directory, file)] = await readFile(file, "utf8");
      }
      return result;
    }
    const before = await outputFiles();
    build();
    assert.deepEqual(await outputFiles(), before);
    await snapshot([]);
    build();
    assert.match(await readFile(path.join(directory, "index.html"), "utf8"), /class="empty-state"/);
    await assert.rejects(readFile(path.join(directory, "ru/sites/fixture-0/index.html")), { code: "ENOENT" });
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});
